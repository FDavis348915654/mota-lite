const uint32_t *font20_glyph(uint32_t cp)
{
    int lo = 0, hi = FONT20_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint32_t v = g_font20_table[mid].cp;
        if (v == cp) return g_font20_bitmap[g_font20_table[mid].idx];
        if (v < cp) lo = mid + 1; else hi = mid - 1;
    }
    return NULL;
}

int font20_advance(uint32_t cp)
{
    int lo = 0, hi = FONT20_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) >> 1;
        uint32_t v = g_font20_table[mid].cp;
        if (v == cp) return g_font20_table[mid].adv;
        if (v < cp) lo = mid + 1; else hi = mid - 1;
    }
    return 0;
}
